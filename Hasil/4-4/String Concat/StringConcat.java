public class StringConcat {
    public static void main(String[] args) {
        String first = "Java";
        String second = "Fundamentals";
        String combined = first + " " + second;

        System.out.println("String pertama: " + first);
        System.out.println("String kedua: " + second);
        System.out.println("String gabungan: " + combined);
    }
}
